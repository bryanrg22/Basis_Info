def tag(code: str, message: str) -> str:
    """``message`` with `` [code]`` at the end, unless it already carries one."""
    if _TAG.search(message):
        return message
    return f"{message} [{code}]"


def code_in(text: str | None) -> str | None:
    """The first error code in ``text`` (a message, a failure reason, a log line), or None."""
    if not text:
        return None
    found = CODE_PATTERN.search(text)
    return found.group(0) if found else None


def all_codes() -> dict[str, str]:
    """``{name: code}`` for every constant on :class:`E`."""
    return {name: value for name, value in vars(E).items() if name.isupper()}
