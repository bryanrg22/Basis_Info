"""Alembic migrations (S1_SPEC §7, BUILD_PLAN §6.5).

* upgrade from an empty database (no ``vector`` extension yet) creates every table,
  enum, trigger function and trigger;
* ``alembic check`` reports no drift between the models and the migrations, and does
  report drift when the models change (so the check is not vacuous);
* downgrade to base removes everything and upgrading again restores it;
* ``0002_outbox_status`` backfills ``status`` from ``delivered_at``, enforces that the
  two agree, and downgrades back to the ``0001`` outbox;
* ``0003_chunks_hnsw`` adds the HNSW cosine index on ``chunks.embedding`` and makes
  published corpus versions immutable, and downgrades back to ``0002``;
* ``0004_photo_objects`` adds ``photo_localizations`` and ``photo_objects`` with their
  checks (normalized ordered box, known source and status, no author on model rows,
  deletion recorded with who) and tenancy key, and downgrades back to ``0003``;
* ``0005_room_grouping`` adds ``rooms.group_key`` (NULL for existing rooms) and
  ``studies.room_aliases`` (``{}`` for existing studies), and downgrades back to ``0004``;
* ``0006_study_failed`` adds ``failed`` to ``study_status`` and ``studies.failure_reason``;
  its downgrade turns failed studies back into ``processing`` and recreates the enum;
* ``0007_invitations`` adds ``invitations`` (normalized email, known role, one outcome
  recorded with who, one open invitation per firm and email) and changes no existing row;
  it downgrades back to ``0006``;
* ``0008_object_prompts`` adds ``object_prompts`` (known status, returned >= 0, tenancy key)
  and ``photo_objects.mask_source``/``mask_reason``/``prompt_id``, backfilling existing
  manual rows (``candidate`` when derived from one, else ``none``) and requiring a mask
  source on manual rows only; it downgrades back to ``0007``;
* ``0009_components_gate`` adds ``components_processing`` and ``components_review`` to
  ``stage`` before ``assets_processing`` and ``studies.components_gate`` (``false`` for
  existing studies, null for new ones); its downgrade refuses while a study or a review is
  at a components stage, else restores ``0008`` exactly;
* ``0011_study_intake`` adds ``studies.intake`` (NULL for existing studies; a non-null value
  must be a JSON object) and downgrades back to ``0010``;
* upgrading at head is a no-op; offline (``--sql``) rendering works.

Each test that changes the schema gets its own throwaway database in the shared
container, so the session-wide test database is never disturbed.
"""

