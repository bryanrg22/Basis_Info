"""Alembic migrations (S1_SPEC §7, BUILD_PLAN §6.5).

* upgrade from an empty database (no ``vector`` extension yet) creates every table,
  enum, trigger function and trigger;
* ``alembic check`` reports no drift between the models and the migrations, and does
  report drift when the models change (so the check is not vacuous);
* downgrade one revision removes everything and upgrading again restores it;
* upgrading at head is a no-op; offline (``--sql``) rendering works.

Each test that changes the schema gets its own throwaway database in the shared
container, so the session-wide test database is never disturbed.
"""

from __future__ import annotations

import asyncio
import io
import uuid
from collections.abc import AsyncIterator

import asyncpg
import pytest
from alembic import command
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from dbtest_support import alembic_config, execute_admin, plain_dsn
from sqlalchemy import Column, MetaData, Text
from sqlalchemy.engine import make_url

from basis.db.models import APPEND_ONLY_TABLES, PG_ENUMS, UPDATED_AT_TABLES, Base

pytestmark = pytest.mark.integration

HEAD = "0001"
EXPECTED_TRIGGERS = (
    {(f"{table}_set_updated_at", table) for table in UPDATED_AT_TABLES}
    | {(f"{table}_append_only", table) for table in APPEND_ONLY_TABLES}
    | {("users_firebase_uid_immutable", "users")}
)
EXPECTED_FUNCTIONS = {"set_updated_at", "forbid_mutation", "forbid_firebase_uid_change"}


@pytest.fixture
async def empty_database_url(database_url: str) -> AsyncIterator[str]:
    name = f"migrations_{uuid.uuid4().hex[:12]}"
    await execute_admin(database_url, f'CREATE DATABASE "{name}"')
    try:
        yield make_url(database_url).set(database=name).render_as_string(hide_password=False)
    finally:
        await execute_admin(database_url, f'DROP DATABASE "{name}" WITH (FORCE)')


async def upgrade(url: str, target: str = "head") -> None:
    # env.py calls asyncio.run(); run it in a worker thread so it gets its own loop.
    await asyncio.to_thread(command.upgrade, alembic_config(url), target)


async def downgrade(url: str, target: str) -> None:
    await asyncio.to_thread(command.downgrade, alembic_config(url), target)


async def snapshot(url: str) -> dict[str, object]:
    """Tables, enum labels, triggers, functions, extensions and version of a database."""
    connection = await asyncpg.connect(plain_dsn(url))
    try:
        tables = {
            r["tablename"]
            for r in await connection.fetch(
                "SELECT tablename FROM pg_tables WHERE schemaname = 'public'"
            )
        }
        enums: dict[str, list[str]] = {}
        for r in await connection.fetch(
            "SELECT t.typname, e.enumlabel FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid "
            "ORDER BY t.typname, e.enumsortorder"
        ):
            enums.setdefault(r["typname"], []).append(r["enumlabel"])
        triggers = {
            (r["tgname"], r["relname"])
            for r in await connection.fetch(
                "SELECT tg.tgname, c.relname FROM pg_trigger tg "
                "JOIN pg_class c ON c.oid = tg.tgrelid WHERE NOT tg.tgisinternal"
            )
        }
        functions = {
            r["proname"]
            for r in await connection.fetch(
                "SELECT p.proname FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace "
                "WHERE n.nspname = 'public' AND p.prolang = "
                "(SELECT oid FROM pg_language WHERE lanname = 'plpgsql')"
            )
        }
        extensions = {
            r["extname"] for r in await connection.fetch("SELECT extname FROM pg_extension")
        }
        version = None
        if "alembic_version" in tables:
            version = await connection.fetchval("SELECT version_num FROM alembic_version")
        return {
            "tables": tables,
            "enums": enums,
            "triggers": triggers,
            "functions": functions,
            "extensions": extensions,
            "version": version,
        }
    finally:
        await connection.close()


def model_tables() -> set[str]:
    return set(Base.metadata.tables)


def model_enums() -> dict[str, list[str]]:
    return {enum.name: list(enum.enums) for enum in PG_ENUMS if enum.name}


def test_migration_history_is_linear_with_expected_head() -> None:
    script = ScriptDirectory.from_config(alembic_config("postgresql+asyncpg://unused/unused"))
    assert script.get_heads() == [HEAD]
    assert [rev.revision for rev in script.walk_revisions()] == [HEAD]


async def test_upgrade_from_empty_creates_everything(empty_database_url: str) -> None:
    before = await snapshot(empty_database_url)
    assert before["tables"] == set()
    assert "vector" not in before["extensions"]  # the migration must install it itself

    await upgrade(empty_database_url)

    after = await snapshot(empty_database_url)
    assert after["tables"] == model_tables() | {"alembic_version"}
    assert after["enums"] == model_enums()
    assert after["triggers"] == EXPECTED_TRIGGERS
    assert after["functions"] == EXPECTED_FUNCTIONS
    assert "vector" in after["extensions"]
    assert after["version"] == HEAD


async def test_alembic_check_reports_no_drift(database_url: str) -> None:
    await asyncio.to_thread(command.check, alembic_config(database_url))


async def test_alembic_check_detects_drift(database_url: str) -> None:
    drifted = MetaData(naming_convention=Base.metadata.naming_convention)
    for table in Base.metadata.sorted_tables:
        table.to_metadata(drifted)
    drifted.tables["orgs"].append_column(Column("not_migrated", Text))
    config = alembic_config(database_url, target_metadata=drifted)
    with pytest.raises(AutogenerateDiffsDetected, match="not_migrated"):
        await asyncio.to_thread(command.check, config)


async def test_downgrade_one_then_upgrade_again(empty_database_url: str) -> None:
    await upgrade(empty_database_url)
    upgraded = await snapshot(empty_database_url)

    await downgrade(empty_database_url, "-1")
    down = await snapshot(empty_database_url)
    assert down["tables"] == {"alembic_version"}
    assert down["version"] is None
    assert down["enums"] == {}
    assert down["triggers"] == set()
    assert down["functions"] == set()
    # The extension is deliberately left installed (see the migration docstring).
    assert "vector" in down["extensions"]

    await upgrade(empty_database_url)
    assert await snapshot(empty_database_url) == upgraded
    await asyncio.to_thread(command.check, alembic_config(empty_database_url))


async def test_upgrade_at_head_is_a_noop(empty_database_url: str) -> None:
    await upgrade(empty_database_url)
    first = await snapshot(empty_database_url)
    await upgrade(empty_database_url)
    assert await snapshot(empty_database_url) == first


async def test_upgrade_with_extension_already_installed(empty_database_url: str) -> None:
    await execute_admin(empty_database_url, "CREATE EXTENSION vector")
    await upgrade(empty_database_url)
    assert (await snapshot(empty_database_url))["version"] == HEAD


def test_offline_sql_rendering() -> None:
    buffer = io.StringIO()
    config = alembic_config("postgresql+asyncpg://user@localhost/offline")
    config.output_buffer = buffer
    command.upgrade(config, "head", sql=True)
    sql = buffer.getvalue()
    assert "CREATE EXTENSION IF NOT EXISTS vector" in sql
    assert "CREATE TYPE stage AS ENUM" in sql
    for table in model_tables():
        assert f"CREATE TABLE {table} " in sql
    assert "CREATE TRIGGER reviews_append_only" in sql
