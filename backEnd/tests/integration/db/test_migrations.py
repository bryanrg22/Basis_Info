async def upgrade(url: str, target: str = "head") -> None:
    # env.py calls asyncio.run(); run it in a worker thread so it gets its own loop.
    await asyncio.to_thread(command.upgrade, alembic_config(url), target)


async def downgrade(url: str, target: str) -> None:
    await asyncio.to_thread(command.downgrade, alembic_config(url), target)


async def snapshot(url: str) -> dict[str, object]:
    """Tables, enum labels, triggers, functions, extensions and version of a database."""
    connection = await asyncpg.connect(plain_dsn(url))
    try:
        tables = {
            r["tablename"]
            for r in await connection.fetch(
                "SELECT tablename FROM pg_tables WHERE schemaname = 'public'"
            )
        }
        enums: dict[str, list[str]] = {}
        for r in await connection.fetch(
            "SELECT t.typname, e.enumlabel FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid "
            "ORDER BY t.typname, e.enumsortorder"
        ):
            enums.setdefault(r["typname"], []).append(r["enumlabel"])
        triggers = {
            (r["tgname"], r["relname"])
            for r in await connection.fetch(
                "SELECT tg.tgname, c.relname FROM pg_trigger tg "
                "JOIN pg_class c ON c.oid = tg.tgrelid WHERE NOT tg.tgisinternal"
            )
        }
        functions = {
            r["proname"]
            for r in await connection.fetch(
                "SELECT p.proname FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace "
                "WHERE n.nspname = 'public' AND p.prolang = "
                "(SELECT oid FROM pg_language WHERE lanname = 'plpgsql')"
            )
        }
        extensions = {
            r["extname"] for r in await connection.fetch("SELECT extname FROM pg_extension")
        }
        version = None
        if "alembic_version" in tables:
            version = await connection.fetchval("SELECT version_num FROM alembic_version")
        return {
            "tables": tables,
            "enums": enums,
            "triggers": triggers,
            "functions": functions,
            "extensions": extensions,
            "version": version,
        }
    finally:
        await connection.close()


def model_tables() -> set[str]:
    return set(Base.metadata.tables)


def model_enums() -> dict[str, list[str]]:
    return {enum.name: list(enum.enums) for enum in PG_ENUMS if enum.name}


def test_migration_history_is_linear_with_expected_head() -> None:
    script = ScriptDirectory.from_config(alembic_config("postgresql+asyncpg://unused/unused"))
    assert script.get_heads() == [HEAD]
    assert [rev.revision for rev in script.walk_revisions()] == HISTORY


async def test_upgrade_from_empty_creates_everything(empty_database_url: str) -> None:
    before = await snapshot(empty_database_url)
    assert before["tables"] == set()
    assert "vector" not in before["extensions"]  # the migration must install it itself

    await upgrade(empty_database_url)

    after = await snapshot(empty_database_url)
    assert after["tables"] == model_tables() | {"alembic_version"}
    assert after["enums"] == model_enums()
    assert after["triggers"] == EXPECTED_TRIGGERS
    assert after["functions"] == EXPECTED_FUNCTIONS
    assert "vector" in after["extensions"]
    assert after["version"] == HEAD


